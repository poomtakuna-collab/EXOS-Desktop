from __future__ import annotations

import ast
import inspect
import json
import sys
import unittest

import src.signal_ledger.canonical_result_adapter as adapter_module
from src.canonical_result import (
    CanonicalBrainResultV1,
    CanonicalContextResultV1,
    CanonicalDiagnosticsV1,
    CanonicalIdentityV1,
    CanonicalPredictionResultV1,
    CanonicalResultV1,
    CanonicalSignalSummaryV1,
    CanonicalStrategyResultV1,
)
from src.signal_ledger import (
    ADAPTER_VERSION_V1,
    SignalRecord,
    SignalSnapshotReference,
    SignalType,
    build_signal_record_from_canonical_result,
)


class CanonicalResultSignalAdapterTest(unittest.TestCase):
    def test_minimal_canonical_result_maps_to_default_signal_candidate(self) -> None:
        signal = build_signal_record_from_canonical_result(CanonicalResultV1())

        self.assertIsInstance(signal, SignalRecord)
        self.assertEqual(signal.symbol, "")
        self.assertEqual(signal.signal_date, "")
        self.assertEqual(signal.snapshot_reference, SignalSnapshotReference())
        self.assertEqual(signal.context_summary, {})
        self.assertEqual(signal.strategy_summary, {})
        self.assertEqual(signal.signal_type, SignalType.UNKNOWN)
        self.assertIsNone(signal.confidence)
        self.assertEqual(signal.notes, (f"Generated by {ADAPTER_VERSION_V1}.",))

    def test_full_canonical_result_maps_available_sections(self) -> None:
        result = CanonicalResultV1(
            identity=CanonicalIdentityV1(
                symbol="aapl",
                timeframe="1D",
                snapshot_id="snapshot-1",
                snapshot_date="2026-07-01",
                analysis_date="2026-07-02",
                source="analysis_pipeline_v2",
            ),
            brain=CanonicalBrainResultV1(
                prediction_summary={"confidence": 71.0, "evidence_count": 24},
            ),
            prediction=CanonicalPredictionResultV1(
                confidence=72.5,
                evidence_count=24,
                probability_positive=64.0,
                expected_return_10d=5.5,
                best_pattern_id="pattern-1",
                best_similarity=89.5,
                notes=("prediction normalized",),
            ),
            context=CanonicalContextResultV1(
                market={"trend": "up", "risk_state": "risk_on"},
                sector={"sector_symbol": "XLK"},
                relative_strength={"rating": "outperform"},
                volume={"volume_state": "high"},
                support_resistance={"nearest_support": 100.0},
                warnings=("sector benchmark unavailable",),
            ),
            strategy=CanonicalStrategyResultV1(
                strategy_score=78.0,
                trade_grade="good",
                entry_quality="acceptable",
                risk_rating="medium",
                reward_risk_ratio=2.2,
                notes=("strategy evaluated",),
            ),
            signal_summary=CanonicalSignalSummaryV1(
                signal_type="setup",
                notes=("manual candidate only",),
            ),
            diagnostics=CanonicalDiagnosticsV1(
                warnings=("read-only candidate",),
                notes=("no persistence",),
            ),
        )

        signal = build_signal_record_from_canonical_result(result)

        self.assertEqual(signal.symbol, "AAPL")
        self.assertEqual(signal.signal_date, "2026-07-02")
        self.assertEqual(signal.snapshot_reference.snapshot_id, "snapshot-1")
        self.assertEqual(signal.snapshot_reference.snapshot_date, "2026-07-01")
        self.assertEqual(signal.snapshot_reference.timeframe, "1D")
        self.assertEqual(signal.snapshot_reference.source, "analysis_pipeline_v2")
        self.assertEqual(signal.context_summary["market"]["trend"], "up")
        self.assertEqual(signal.context_summary["warnings"], ["sector benchmark unavailable"])
        self.assertEqual(signal.strategy_summary["strategy_score"], 78.0)
        self.assertEqual(signal.strategy_summary["risk_rating"], "medium")
        self.assertEqual(signal.strategy_summary["prediction_summary"]["confidence"], 72.5)
        self.assertEqual(signal.strategy_summary["prediction_summary"]["evidence_count"], 24)
        self.assertEqual(signal.signal_type, SignalType.SETUP)
        self.assertEqual(signal.confidence, 72.5)
        self.assertIn("manual candidate only", signal.notes)
        self.assertIn("prediction normalized", signal.notes)
        self.assertIn("strategy evaluated", signal.notes)
        self.assertIn("read-only candidate", signal.notes)
        self.assertIn("no persistence", signal.notes)

    def test_signal_summary_overrides_core_identity_when_available(self) -> None:
        result = CanonicalResultV1(
            identity=CanonicalIdentityV1(
                symbol="MSFT",
                timeframe="1D",
                snapshot_id="identity-snapshot",
                snapshot_date="2026-07-01",
                analysis_date="2026-07-02",
            ),
            signal_summary=CanonicalSignalSummaryV1(
                symbol="NVDA",
                signal_date="2026-07-03",
                timeframe="1W",
                signal_type="breakout",
                confidence=88.0,
                snapshot_id="summary-snapshot",
                snapshot_date="2026-07-02",
                context_summary={"market": {"trend": "up"}},
                strategy_summary={"strategy_score": 91.0},
                prediction_summary={"confidence": 88.0},
            ),
        )

        signal = build_signal_record_from_canonical_result(result)

        self.assertEqual(signal.symbol, "NVDA")
        self.assertEqual(signal.signal_date, "2026-07-03")
        self.assertEqual(signal.snapshot_reference.snapshot_id, "summary-snapshot")
        self.assertEqual(signal.snapshot_reference.snapshot_date, "2026-07-02")
        self.assertEqual(signal.snapshot_reference.timeframe, "1W")
        self.assertEqual(signal.context_summary, {"market": {"trend": "up"}})
        self.assertEqual(signal.strategy_summary["strategy_score"], 91.0)
        self.assertEqual(signal.strategy_summary["prediction_summary"], {"confidence": 88.0})
        self.assertEqual(signal.signal_type, SignalType.BREAKOUT)
        self.assertEqual(signal.confidence, 88.0)

    def test_missing_context_strategy_and_prediction_are_safe(self) -> None:
        result = CanonicalResultV1(
            identity=CanonicalIdentityV1(
                symbol="AAPL",
                snapshot_date="2026-07-01",
            )
        )

        signal = build_signal_record_from_canonical_result(result)

        self.assertEqual(signal.symbol, "AAPL")
        self.assertEqual(signal.signal_date, "2026-07-01")
        self.assertEqual(signal.context_summary, {})
        self.assertEqual(signal.strategy_summary, {})
        self.assertEqual(signal.signal_type, SignalType.UNKNOWN)
        self.assertIsNone(signal.confidence)

    def test_malformed_optional_fields_do_not_raise(self) -> None:
        result = CanonicalResultV1(
            identity=CanonicalIdentityV1(symbol="AAPL"),
            prediction="not-a-prediction",  # type: ignore[arg-type]
            context={"market": "not-a-context"},  # type: ignore[arg-type]
            strategy=object(),  # type: ignore[arg-type]
            signal_summary=object(),  # type: ignore[arg-type]
        )

        signal = build_signal_record_from_canonical_result(result)

        self.assertEqual(signal.symbol, "AAPL")
        self.assertEqual(signal.context_summary, {})
        self.assertEqual(signal.strategy_summary, {})
        self.assertEqual(signal.signal_type, SignalType.UNKNOWN)
        self.assertIsNone(signal.confidence)

    def test_custom_signal_type_is_preserved_as_string(self) -> None:
        result = CanonicalResultV1(
            signal_summary=CanonicalSignalSummaryV1(signal_type="custom-research")
        )

        signal = build_signal_record_from_canonical_result(result)

        self.assertEqual(signal.signal_type, "custom-research")
        self.assertEqual(signal.to_dict()["signal_type"], "custom-research")

    def test_deterministic_serialization(self) -> None:
        result = CanonicalResultV1(
            identity=CanonicalIdentityV1(
                symbol="AAPL",
                timeframe="1D",
                snapshot_id="snapshot-1",
                snapshot_date="2026-07-01",
            ),
            brain=CanonicalBrainResultV1(
                prediction_summary={"confidence": 70.0, "evidence_count": 10},
            ),
            context=CanonicalContextResultV1(market={"trend": "up"}),
        )

        first = build_signal_record_from_canonical_result(result).to_dict()
        second = build_signal_record_from_canonical_result(result).to_dict()

        self.assertEqual(first, second)
        json.dumps(first, sort_keys=True)

    def test_adapter_does_not_import_database_ai_network_broker_or_gui_modules(self) -> None:
        blocked_module_roots = {
            "openai",
            "anthropic",
            "yfinance",
            "requests",
            "httpx",
            "urllib3",
            "alpaca",
            "ib_insync",
            "sqlite3",
            "src.gui",
            "src.database",
        }
        imported_roots: set[str] = set()

        tree = ast.parse(inspect.getsource(adapter_module))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported_roots.update(alias.name for alias in node.names)
            if isinstance(node, ast.ImportFrom) and node.module:
                imported_roots.add(node.module)

        self.assertTrue(blocked_module_roots.isdisjoint(imported_roots))

    def test_importing_adapter_does_not_load_blocked_runtime_modules(self) -> None:
        blocked_module_roots = {
            "openai",
            "anthropic",
            "yfinance",
            "requests",
            "httpx",
            "urllib3",
            "alpaca",
            "ib_insync",
            "sqlite3",
        }
        before = set(sys.modules)

        import src.signal_ledger.canonical_result_adapter  # noqa: F401

        imported = set(sys.modules) - before
        imported_roots = {name.split(".")[0] for name in imported}
        self.assertTrue(blocked_module_roots.isdisjoint(imported_roots))


if __name__ == "__main__":
    unittest.main()
